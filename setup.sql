-- I-paste ito sa Supabase > SQL Editor > New query, tapos i-click ang Run.

create table if not exists destinations (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  address text,
  category text,
  image text,
  historical_info text,
  cultural_significance text,
  latitude double precision,
  longitude double precision,
  created_at timestamptz default now()
);

create table if not exists quiz_questions (
  id bigint generated by default as identity primary key,
  destination_id bigint references destinations(id) on delete cascade,
  question text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_answer text not null
);

create table if not exists user_progress (
  id bigint generated by default as identity primary key,
  destination_id bigint references destinations(id) on delete cascade,
  quiz_score integer,
  completed integer default 0,
  completed_at timestamptz
);

create table if not exists panorama_points (
  id bigint generated by default as identity primary key,
  destination_id bigint not null references destinations(id) on delete cascade,
  name text,
  panorama_image text,
  latitude double precision,
  longitude double precision,
  rotation double precision default 0,
  is_entry_point integer default 0,
  created_at timestamptz default now()
);

create table if not exists panorama_connections (
  id bigint generated by default as identity primary key,
  from_point_id bigint not null references panorama_points(id) on delete cascade,
  to_point_id bigint not null references panorama_points(id) on delete cascade,
  hotspot_x double precision,
  hotspot_y double precision,
  direction_angle double precision,
  label text
);

-- Buksan ang access (para sa school project / walang login).
-- Sinumang may app ay pwedeng mag-read/write. Para sa production, mag-add ng auth.
alter table destinations enable row level security;
alter table quiz_questions enable row level security;
alter table user_progress enable row level security;
alter table panorama_points enable row level security;
alter table panorama_connections enable row level security;

create policy "open destinations" on destinations for all using (true) with check (true);
create policy "open quiz_questions" on quiz_questions for all using (true) with check (true);
create policy "open user_progress" on user_progress for all using (true) with check (true);
create policy "open panorama_points" on panorama_points for all using (true) with check (true);
create policy "open panorama_connections" on panorama_connections for all using (true) with check (true);

-- Storage bucket para sa mga larawan
insert into storage.buckets (id, name, public)
values ('destination-images', 'destination-images', true)
on conflict (id) do nothing;

create policy "open images read" on storage.objects for select
  using (bucket_id = 'destination-images');
create policy "open images insert" on storage.objects for insert
  with check (bucket_id = 'destination-images');
create policy "open images update" on storage.objects for update
  using (bucket_id = 'destination-images');
create policy "open images delete" on storage.objects for delete
  using (bucket_id = 'destination-images');
